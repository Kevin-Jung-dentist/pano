const fs=require('node:fs');
module.exports=function buildAdmin(){
 const assets={};
 for(const file of ['index.html','admin.css','admin.js','new/index.html','new/create.js']){
  const content=fs.readFileSync('admin/'+file,'utf8');
  const type=file.endsWith('.html')?'text/html; charset=utf-8':file.endsWith('.css')?'text/css; charset=utf-8':'text/javascript; charset=utf-8';
  assets['/admin/'+file]={content,type};
 }
 fs.writeFileSync('server/admin-assets.mjs','// Generated by scripts/build-admin.js; only served after administrator authorization.\nexport const adminAssets='+JSON.stringify(assets)+';\n');
 if(fs.existsSync('dist/admin'))throw Error('Administrator files must not exist in the public static directory');
};
